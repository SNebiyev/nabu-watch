// ---------------------------------------------------------------------------
// minUsableBodyLen threshold
// ---------------------------------------------------------------------------

func TestMinUsableBodyLen_rejectsBlockPages(t *testing.T) {
	// A typical Akamai "Access Denied" block page has ~100-3000 bytes of
	// visible text.  The threshold must reject these but accept real pages.
	akamaiBlockBody := "Access Denied You don't have permission to access this resource. Reference #18.abcdef12.1700000000"
	if len(akamaiBlockBody) >= minUsableBodyLen {
		t.Fatalf("Akamai block page text (%d bytes) should be below minUsableBodyLen (%d)", len(akamaiBlockBody), minUsableBodyLen)
	}

	// A real Terms of Service page has at least tens of thousands of bytes.
	realPageLen := 50_000
	if realPageLen < minUsableBodyLen {
		t.Fatalf("real page (%d bytes) should be above minUsableBodyLen (%d)", realPageLen, minUsableBodyLen)
	}
}

