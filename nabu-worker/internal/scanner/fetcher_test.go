// isBlockPage
// ---------------------------------------------------------------------------

func TestIsBlockPage(t *testing.T) {
	tests := []struct {
		name     string
		bodyText string
		want     bool
	}{
		// ── Positive cases ────────────────────────────────────────────────
		{
			name:     "Akamai reference # pattern",
			bodyText: "Access Denied You don't have permission. Reference #18.abcdef12.1700000000.12345678",
			want:     true,
		},
		{
			name:     "Akamai reference id",
			bodyText: "Error Reference ID: 12345678",
			want:     true,
		},
		{
			name:     "Akamai technologies footer",
			bodyText: "Generated by Akamai Technologies for example.com",
			want:     true,
		},
		{
			name:     "Cloudflare Ray ID",
			bodyText: "Sorry, you have been blocked. Performance & security by Cloudflare. Ray ID: 7abc123def456789",
			want:     true,
		},
		{
			name:     "Cloudflare brand",
			bodyText: "Checking your browser before accessing example.com. This process is automatic. Powered by Cloudflare.",
			want:     true,
		},
		{
			name:     "403 Forbidden text",
			bodyText: "403 Forbidden - You do not have permission to access this resource.",
			want:     true,
		},
		{
			name:     "DDoS protection page",
			bodyText: "DDoS protection by SomeService. Please wait while we verify your browser.",
			want:     true,
		},
		{
			name:     "Enable JavaScript and cookies",
			bodyText: "Please enable JavaScript and cookies to continue.",
			want:     true,
		},
		{
			name:     "Human verification",
			bodyText: "Please verify you are a human to access this page.",
			want:     true,
		},
		{
			name:     "case insensitive",
			bodyText: "ACCESS DENIED - your request has been blocked",
			want:     true,
		},

		// ── Negative cases ────────────────────────────────────────────────
		{
			name:     "legitimate terms of service page",
			bodyText: "Allgemeine Geschäftsbedingungen. Nutzungsbedingungen für shop.example.de. Widerrufsrecht nach deutschem Recht.",
			want:     false,
		},
		{
			name:     "empty body",
			bodyText: "",
			want:     false,
		},
		{
			name:     "normal privacy policy",
			bodyText: "Datenschutzerklärung. Wir verwenden Cookies um unsere Dienste bereitzustellen.",
			want:     false,
		},
		{
			name:     "page mentioning access control legitimately",
			bodyText: "Users can manage role-based access control from the settings page.",
			want:     false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := isBlockPage(tt.bodyText)
			if got != tt.want {
				t.Errorf("isBlockPage(%q) = %v, want %v", tt.bodyText[:min(len(tt.bodyText), 60)], got, tt.want)
			}
		})
	}
}

