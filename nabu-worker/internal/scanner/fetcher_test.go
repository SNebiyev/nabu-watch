func parseDoc(t *testing.T, html string) *goquery.Document {
	t.Helper()
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(html))
	if err != nil {
		t.Fatalf("parse html: %v", err)
	}
	return doc
}

// paddedHTML returns an HTML document whose rendered length exceeds
// wafBlockHTMLThreshold without triggering block-page markers, so tests can
// isolate the link-count gate from the size/body gates.
func paddedHTML(title, body string) string {
	filler := strings.Repeat("neutral marketing copy. ", 600) // >10 KB
	return "<html><head><title>" + title + "</title></head><body>" +
		body + "<p>" + filler + "</p></body></html>"
}

func TestIsUsableFetchResult(t *testing.T) {
	tests := []struct {
		name string
		html string
		want bool
	}{
		{
			name: "real homepage with many links",
			html: paddedHTML("Welcome",
				`<a href="/a">A</a><a href="/b">B</a><a href="/c">C</a><a href="/d">D</a>`),
			want: true,
		},
		{
			name: "WAF interstitial — large HTML, zero links (shop.example.de symptom)",
			html: paddedHTML("Welcome", `<div>Loading...</div>`),
			want: false,
		},
		{
			name: "WAF interstitial — only 2 links, otherwise healthy-looking",
			html: paddedHTML("Welcome", `<a href="/x">X</a><a href="/y">Y</a>`),
			want: false,
		},
		{
			name: "block title rejected even with many links",
			html: paddedHTML("Access Denied",
				`<a href="/a">A</a><a href="/b">B</a><a href="/c">C</a><a href="/d">D</a>`),
			want: false,
		},
		{
			name: "tiny HTML rejected even with links",
			html: "<html><head><title>ok</title></head><body>" +
				`<a href="/a">A</a><a href="/b">B</a><a href="/c">C</a>` +
				"</body></html>",
			want: false,
		},
		{
			name: "cloudflare body markers rejected",
			html: "<html><head><title>ok</title></head><body>" +
				"Checking your browser before accessing example.com. Powered by Cloudflare. Ray ID: abc" +
				`<a href="/a">A</a><a href="/b">B</a><a href="/c">C</a><a href="/d">D</a>` +
				strings.Repeat("x", 11000) +
				"</body></html>",
			want: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := isUsableFetchResult(parseDoc(t, tt.html))
			if got != tt.want {
				t.Errorf("isUsableFetchResult() = %v, want %v", got, tt.want)
			}
		})
	}
}

func TestIsUsableFetchResult_nilDoc(t *testing.T) {
	if isUsableFetchResult(nil) {
		t.Error("nil doc should not be usable")
	}
}
